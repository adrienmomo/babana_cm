#!/bin/sh
# Dev server 75.119.155.162 -- writes /etc/babana/babana.env, ONCE, with freshly generated
# secrets. Read by systemd (Odoo), Node --env-file (realtime, via pm2) and docker compose (data
# services). Never committed, never copied from infra/env/.env.example (its values are public).
#
#   sudo GOOGLE_OAUTH_CLIENT_IDS=<id>.apps.googleusercontent.com sh infra/devserver/gen-env.sh
#
# Refuses to overwrite: regenerating would change the database and MinIO passwords under data
# that already uses them. To rotate a secret, edit the file by hand and restart the service.
set -eu

ENV_FILE="${BABANA_ENV_FILE:-/etc/babana/babana.env}"
die() { printf 'ÉCHEC : %s\n' "$1" >&2; exit 1; }

[ "$(id -u)" = 0 ] || die "à exécuter en root (sudo)."
[ ! -e "$ENV_FILE" ] || die "$ENV_FILE existe déjà -- jamais régénéré (voir l'en-tête)."
: "${GOOGLE_OAUTH_CLIENT_IDS:?GOOGLE_OAUTH_CLIENT_IDS obligatoire -- l'identifiant client OAuth (pas un secret).}"
command -v openssl >/dev/null || die "openssl absent."
getent group babana >/dev/null || die "groupe babana absent -- créer l'utilisateur de service d'abord."

# Hex only: no character that systemd, Node or compose would read differently.
secret() { openssl rand -hex 32; }
PG_PASSWORD=$(secret)
MINIO_PASSWORD=$(secret)

umask 077
mkdir -p "$(dirname "$ENV_FILE")"
# The directory must let babana through too: under umask 077 it is created 700 root, and the
# file's own 640 root:babana is then never reached.
chown root:babana "$(dirname "$ENV_FILE")"
chmod 750 "$(dirname "$ENV_FILE")"
cat > "$ENV_FILE" <<EOF
# Generated by infra/devserver/gen-env.sh on $(date -u +%FT%TZ). Dev server only. Never commit.

# --- PostgreSQL (docker) and Odoo's connection (libpq) ---
POSTGRES_USER=babana
POSTGRES_PASSWORD=${PG_PASSWORD}
PGHOST=127.0.0.1
PGPORT=5432
PGUSER=babana
PGPASSWORD=${PG_PASSWORD}

# --- Shared secrets ---
ADMIN_PASSWORD=$(secret)
JWT_SECRET=$(secret)
REALTIME_SHARED_SECRET=$(secret)

# --- MinIO (docker) and Odoo's S3 client ---
MINIO_ROOT_USER=babana
MINIO_ROOT_PASSWORD=${MINIO_PASSWORD}
S3_ENDPOINT=http://127.0.0.1:9000
S3_BUCKET=babana-documents
S3_ACCESS_KEY=babana
S3_SECRET_KEY=${MINIO_PASSWORD}
S3_PUBLIC_ENDPOINT=https://storage.babana.dev

# --- Odoo ---
# Trip-share links: https://\${BABANA_DOMAIN}/s/<token> (controllers/share.py).
BABANA_DOMAIN=share.babana.dev
REALTIME_INTERNAL_URL=http://127.0.0.1:3000
GOOGLE_OAUTH_CLIENT_IDS=${GOOGLE_OAUTH_CLIENT_IDS}
GOOGLE_JWKS_URL=https://www.googleapis.com/oauth2/v3/certs
# No GOOGLE_JWKS_URL_MOCK: no simulated issuer on this server (D75).
# Simulated routing, 127.0.0.1 only -- no Google Routes adapter yet.
GOOGLE_ROUTING_URL=http://127.0.0.1:4001/route
SMTP_HOST=127.0.0.1
SMTP_PORT=1025
SMTP_USER=
SMTP_PASSWORD=
SMTP_FROM=no-reply@babana.dev
PUSH_PROVIDER=console
# No SMS provider yet: messages go to Odoo's log (journalctl -u babana-odoo), and every OTP is
# 000000 (decided 2026-11-09). Anyone who knows a seeded number can sign in with it -- acceptable
# on this server only. Ignored by Odoo as soon as SMS_PROVIDER is a real gateway (sms.py).
SMS_PROVIDER=console
OTP_DEV_FIXED_CODE=000000

# --- Realtime service ---
REDIS_URL=redis://127.0.0.1:6379
ODOO_INTERNAL_URL=http://127.0.0.1:8069
EOF
chown root:babana "$ENV_FILE"
chmod 640 "$ENV_FILE"
echo "$ENV_FILE écrit (640 root:babana). ADMIN_PASSWORD : sudo grep ^ADMIN_PASSWORD= $ENV_FILE"
